def update_window(version, current, date, notes, folder, windows):
    """HTML of the update window: what is new and how to install the new version step by step."""
    new = f'<h3>Що нового</h3><p>{notes}</p>' if notes else ''
    where = (f'<p style="color:#7a6f60">Програма зараз лежить тут:<br><i>{folder}</i></p>' if windows else '')
    return f"""<h2 style="color:#2f6f4f">Вийшла нова версія {version}</h2>
<p>Випуск{date}. У вас версія {current}.</p>
{new}
<h3>Як встановити оновлення</h3>
<ol>
<li>Натисніть <b>«Завантажити»</b>: браузер завантажить zip-архів нової версії.</li>
<li>Закрийте Press Start UA Launcher.</li>
<li>Відкрийте завантажений архів (подвійний клік) і в ньому папку <i>Press Start UA Launcher</i>.</li>
<li>Виділіть усе, що в ній є (<b>Ctrl+A</b>), і перетягніть у папку програми
(кнопка <b>«Відкрити папку програми»</b>). На питання Windows оберіть <b>«Замінити файли»</b>.</li>
<li>Запустіть <b>Press Start UA Launcher.exe</b> як завжди.</li>
</ol>
{where}
<p><b>Ваші налаштування і завантажені патчі збережуться</b>: вони лежать у папці <i>data</i>, а в архіві вона порожня.</p>
<p style="color:#7a6f60">Можна й інакше: розпакуйте нову версію в окрему папку і перенесіть туди стару
папку <i>data</i>, а стару програму видаліть.</p>
<p style="color:#7a6f60">Переклади ігор оновлюються й без нової версії програми: список ігор і патчі
завантажуються з інтернету під час кожного запуску.</p>"""


